function run<T>(tx: Tx | undefined, fn: (tx: Tx) => Promise<T>): Promise<T> {
  return tx ? fn(tx) : withTx(fn);
}

// ───────────── Receivables (invoices) ─────────────

export type InvoiceInput = {
  type: InvoiceType;
  partnerId?: string | null;
  contactId?: string | null;
  description: string;
  issueDate: Date;
  dueDate: Date;
  paymentTerms?: string | null;
  lines: { description: string; itemId?: string | null; quantity: DecimalLike; unitPrice: DecimalLike; unitCost?: DecimalLike }[];
  supplyOrderId?: string | null;
  settlementId?: string | null;
};

export async function createInvoice(actor: Actor, input: InvoiceInput, tx?: Tx) {
  if (!input.lines.length) throw new AppError("An invoice needs at least one line.");
  if (!input.partnerId && !input.contactId) throw new AppError("Choose who owes this amount (partner or contact).");
  if (input.dueDate < input.issueDate) throw new AppError("Due date cannot be before the issue date.");
  const lines = input.lines.map((l) => {
    const q = qty(l.quantity);
    if (q.lte(0)) throw new AppError("Line quantities must be greater than zero.");
    if (D(l.unitPrice).isNegative()) throw new AppError("Unit prices cannot be negative.");
    return { description: l.description, itemId: l.itemId ?? null, quantity: q, unitPrice: qty(l.unitPrice), unitCost: qty(l.unitCost ?? 0), lineTotal: money(q.times(D(l.unitPrice))), lineCost: money(q.times(D(l.unitCost ?? 0))) };
  });
  const amount = money(sum(lines.map((l) => l.lineTotal)));
  if (amount.lte(0)) throw new AppError("Invoice amount must be greater than zero.");
  return run(tx, async (tx) => {
    const inv = await tx.invoice.create({
      data: {
        number: await nextCode(tx, "INV", 5, { yearly: true }), type: input.type, partnerId: input.partnerId ?? null, contactId: input.contactId ?? null,
        description: input.description, issueDate: input.issueDate, dueDate: input.dueDate, paymentTerms: input.paymentTerms,
        amount: amount.toString(), costAmount: money(sum(lines.map((l) => l.lineCost))).toString(),
        supplyOrderId: input.supplyOrderId ?? null, settlementId: input.settlementId ?? null, createdById: actor.id,
        lines: { create: lines.map((l) => ({ ...l, quantity: l.quantity.toString(), unitPrice: l.unitPrice.toString(), unitCost: l.unitCost.toString(), lineTotal: l.lineTotal.toString(), lineCost: l.lineCost.toString() })) },
      },
    });
    await audit(tx, { userId: actor.id, action: "INVOICE_CREATE", entityType: "Invoice", entityId: inv.id, after: inv });
    return inv;
  });
}

export async function cancelInvoice(actor: Actor, id: string, reason: string) {
  if (!reason?.trim()) throw new AppError("A cancellation reason is required.");
  return withTx(async (tx) => {
    const inv = await tx.invoice.findUnique({ where: { id } });
    if (!inv) throw new NotFoundError("Invoice");
    if (inv.status === "CANCELLED") throw new AppError("Invoice is already cancelled.");
    if (D(inv.amountPaid).gt(0)) throw new AppError("Void the payments applied to this invoice before cancelling it.");
    if (inv.type === "SUPPLY") throw new AppError("Supply invoices follow delivered goods and cannot be cancelled. Record a stock return and a credit (negative-adjustment) invoice instead.");
    if (inv.settlementId) throw new AppError("This invoice was generated by a settlement. Void the settlement instead.");
    const after = await tx.invoice.update({ where: { id }, data: { status: "CANCELLED", cancelledAt: new Date(), cancelReason: reason } });
    await audit(tx, { userId: actor.id, action: "INVOICE_CANCEL", entityType: "Invoice", entityId: id, summary: reason, before: inv, after });
    return after;
  });
}

// ───────────── Payables (bills) — every owner expense is a bill ─────────────

export type BillInput = {
  category: ExpenseCategory;
  contactId?: string | null;
  partnerId?: string | null;
  payeeName: string;
  description: string;
  billDate: Date;
  dueDate: Date;
  amount: DecimalLike;
  paymentTerms?: string | null;
  settlementId?: string | null;
};

export async function createBill(actor: Actor, input: BillInput, tx?: Tx) {
  const amount = money(input.amount);
  if (amount.lte(0)) throw new AppError("Amount must be greater than zero.");
  if (input.dueDate < input.billDate) throw new AppError("Due date cannot be before the bill date.");
  return run(tx, async (tx) => {
    const bill = await tx.bill.create({
      data: {
        number: await nextCode(tx, "BILL", 5, { yearly: true }), category: input.category, contactId: input.contactId ?? null, partnerId: input.partnerId ?? null,
        payeeName: input.payeeName, description: input.description, billDate: input.billDate, dueDate: input.dueDate, amount: amount.toString(),
        paymentTerms: input.paymentTerms, settlementId: input.settlementId ?? null, createdById: actor.id,
      },
    });
    await audit(tx, { userId: actor.id, action: "BILL_CREATE", entityType: "Bill", entityId: bill.id, after: bill });
    return bill;
  });
}

export async function cancelBill(actor: Actor, id: string, reason: string) {
  if (!reason?.trim()) throw new AppError("A cancellation reason is required.");
  return withTx(async (tx) => {
    const bill = await tx.bill.findUnique({ where: { id } });
    if (!bill) throw new NotFoundError("Bill");
    if (bill.status === "CANCELLED") throw new AppError("Bill is already cancelled.");
    if (D(bill.amountPaid).gt(0)) throw new AppError("Void the payments applied to this bill before cancelling it.");
    if (bill.settlementId) throw new AppError("This bill was generated by a settlement. Void the settlement instead.");
    const after = await tx.bill.update({ where: { id }, data: { status: "CANCELLED", cancelledAt: new Date(), cancelReason: reason } });
    await audit(tx, { userId: actor.id, action: "BILL_CANCEL", entityType: "Bill", entityId: id, summary: reason, before: bill, after });
    return after;
  });
}

// ───────────── Payments ─────────────

export type AllocationInput = { invoiceId?: string | null; billId?: string | null; amount: DecimalLike };

export type PaymentInput = {
  direction: PaymentDirection;
  paymentDate: Date;
  amount: DecimalLike;
  method: PaymentMethod;
  reference?: string | null;
  partyName: string;
  partnerId?: string | null;
  contactId?: string | null;
  notes?: string | null;
  salesReportId?: string | null;
  allocations: AllocationInput[];
};

/** Applies allocations to invoices/bills, locking each document row and validating balances. */
async function applyAllocations(tx: Tx, paymentId: string, direction: PaymentDirection, paymentAmount: DecimalLike, allocations: AllocationInput[], partnerScope?: string | null) {
  const existing = await tx.paymentAllocation.aggregate({ where: { paymentId }, _sum: { amount: true } });
  let total = D(existing._sum.amount);
  for (const a of allocations) {
    const amt = money(a.amount);
    if (amt.lte(0)) continue;
    if (!!a.invoiceId === !!a.billId) throw new AppError("Each allocation must target exactly one invoice or bill.");
    if (a.invoiceId) {
      if (direction !== "IN") throw new AppError("Outgoing payments can only be applied to bills.");
      await tx.$queryRaw`SELECT id FROM "Invoice" WHERE id = ${a.invoiceId} FOR UPDATE`;
      const inv = await tx.invoice.findUnique({ where: { id: a.invoiceId } });
      if (!inv) throw new NotFoundError("Invoice");
      if (partnerScope !== undefined && partnerScope !== null && inv.partnerId !== partnerScope) throw new AppError(`Invoice ${inv.number} belongs to a different party.`);
      if (inv.status === "CANCELLED") throw new AppError(`Invoice ${inv.number} is cancelled.`);
      const balance = D(inv.amount).minus(D(inv.amountPaid));
      if (amt.gt(balance)) throw new AppError(`Allocation to ${inv.number} (${amt.toFixed(2)}) exceeds its balance (${balance.toFixed(2)}).`);
      const paid = D(inv.amountPaid).plus(amt);
      await tx.invoice.update({ where: { id: inv.id }, data: { amountPaid: paid.toString(), status: statusFromPaid(inv.amount, paid) } });
      await tx.paymentAllocation.create({ data: { paymentId, invoiceId: inv.id, amount: amt.toString() } });
    } else if (a.billId) {
      if (direction !== "OUT") throw new AppError("Incoming payments can only be applied to invoices.");
      await tx.$queryRaw`SELECT id FROM "Bill" WHERE id = ${a.billId} FOR UPDATE`;
      const bill = await tx.bill.findUnique({ where: { id: a.billId } });
      if (!bill) throw new NotFoundError("Bill");
      if (bill.status === "CANCELLED") throw new AppError(`Bill ${bill.number} is cancelled.`);
      const balance = D(bill.amount).minus(D(bill.amountPaid));
      if (amt.gt(balance)) throw new AppError(`Allocation to ${bill.number} (${amt.toFixed(2)}) exceeds its balance (${balance.toFixed(2)}).`);
      const paid = D(bill.amountPaid).plus(amt);
      await tx.bill.update({ where: { id: bill.id }, data: { amountPaid: paid.toString(), status: statusFromPaid(bill.amount, paid) } });
      await tx.paymentAllocation.create({ data: { paymentId, billId: bill.id, amount: amt.toString() } });
    }
    total = total.plus(amt);
  }
  if (total.gt(D(paymentAmount))) throw new AppError("Allocations exceed the payment amount.");
}

async function reverseAllocations(tx: Tx, paymentId: string) {
  const allocs = await tx.paymentAllocation.findMany({ where: { paymentId } });
  for (const a of allocs) {
    if (a.invoiceId) {
      const inv = await tx.invoice.findUniqueOrThrow({ where: { id: a.invoiceId } });
      const paid = D(inv.amountPaid).minus(D(a.amount));
      await tx.invoice.update({ where: { id: inv.id }, data: { amountPaid: paid.toString(), status: inv.status === "CANCELLED" ? "CANCELLED" : statusFromPaid(inv.amount, paid) } });
    }
    if (a.billId) {
      const bill = await tx.bill.findUniqueOrThrow({ where: { id: a.billId } });
      const paid = D(bill.amountPaid).minus(D(a.amount));
      await tx.bill.update({ where: { id: bill.id }, data: { amountPaid: paid.toString(), status: bill.status === "CANCELLED" ? "CANCELLED" : statusFromPaid(bill.amount, paid) } });
    }
  }
  // Allocation rows are kept (history); the payment's VOIDED/REJECTED status marks them inactive.
}

export async function recordPayment(actor: Actor, input: PaymentInput, opts: { status?: PaymentRecordStatus } = {}, tx?: Tx) {
  const amount = money(input.amount);
  if (amount.lte(0)) throw new AppError("Payment amount must be greater than zero.");
  if (!input.partyName?.trim()) throw new AppError("Payer / payee name is required.");
  const status = opts.status ?? "CONFIRMED";
  return run(tx, async (tx) => {
    const payment = await tx.payment.create({
      data: {
        number: await nextCode(tx, input.direction === "IN" ? "RCPT" : "PAY", 5, { yearly: true }), direction: input.direction, status,
        paymentDate: input.paymentDate, amount: amount.toString(), method: input.method, reference: input.reference, partyName: input.partyName,
        partnerId: input.partnerId ?? null, contactId: input.contactId ?? null, notes: input.notes, salesReportId: input.salesReportId ?? null, createdById: actor.id,
        ...(status === "CONFIRMED" ? { verifiedById: actor.id, verifiedAt: new Date() } : {}),
      },
    });
    if (status === "CONFIRMED") {
      await applyAllocations(tx, payment.id, input.direction, amount, input.allocations, input.partnerId);
    } else {
      // Pending: store intended allocations validated against balances now; balances move on verification.
      for (const a of input.allocations) {
        if (D(a.amount).lte(0)) continue;
        await tx.paymentAllocation.create({ data: { paymentId: payment.id, invoiceId: a.invoiceId ?? null, billId: a.billId ?? null, amount: money(a.amount).toString() } });
      }
      const total = sum(input.allocations.map((a) => a.amount));
      if (total.gt(amount)) throw new AppError("Allocations exceed the payment amount.");
    }
    await audit(tx, { userId: actor.id, action: "PAYMENT_CREATE", entityType: "Payment", entityId: payment.id, after: { payment, allocations: input.allocations } });
    return payment;
  });
}

/** Apply an existing confirmed payment's unapplied amount to more documents. */
export async function allocatePayment(actor: Actor, paymentId: string, allocations: AllocationInput[]) {
  return withTx(async (tx) => {
    const p = await tx.payment.findUnique({ where: { id: paymentId } });
    if (!p) throw new NotFoundError("Payment");
    if (p.status !== "CONFIRMED") throw new AppError("Only confirmed payments can be allocated.");
    await applyAllocations(tx, p.id, p.direction, p.amount, allocations, p.partnerId);
    await audit(tx, { userId: actor.id, action: "PAYMENT_ALLOCATE", entityType: "Payment", entityId: p.id, after: allocations });
  });
}

/** Partner submits proof of payment; finance verifies before balances change. */
export async function submitPartnerPayment(actor: Actor, input: Omit<PaymentInput, "direction" | "partyName" | "partnerId" | "contactId">) {
  if (actor.role !== "PARTNER" || !actor.partnerId) throw new ForbiddenError();
  const partnerId = actor.partnerId;
  return withTx(async (tx) => {
    const partner = await tx.partner.findUniqueOrThrow({ where: { id: partnerId } });
    for (const a of input.allocations) {
      if (a.billId) throw new ForbiddenError();
      if (!a.invoiceId) continue;
      const inv = await tx.invoice.findUnique({ where: { id: a.invoiceId } });
      if (!inv || inv.partnerId !== partnerId) throw new ForbiddenError("You can only pay your own invoices.");
      if (D(a.amount).gt(D(inv.amount).minus(D(inv.amountPaid)))) throw new AppError(`Amount for ${inv.number} exceeds its balance.`);
    }
    const p = await recordPayment(actor, { ...input, direction: "IN", partyName: partner.businessName, partnerId }, { status: "PENDING_VERIFICATION" }, tx);
    await notify("PAYMENT_SUBMITTED", { title: `${partner.businessName} submitted a payment`, body: `${input.method} ${money(input.amount).toFixed(2)} – ref ${input.reference ?? "n/a"}`, link: `/finance/payments/${p.id}`, severity: "INFO", dedupeKey: `pay-${p.id}` }, tx);
    return p;
  });
}

export async function verifyPayment(actor: Actor, paymentId: string, approve: boolean, notes?: string | null) {
  return withTx(async (tx) => {
    const p = await tx.payment.findUnique({ where: { id: paymentId }, include: { allocations: true } });
    if (!p) throw new NotFoundError("Payment");
    if (p.status !== "PENDING_VERIFICATION") throw new AppError("Payment is not awaiting verification.");
    if (approve) {
      // Daily pay-ins are re-split at verification against the balances as they are now.
      const intended = p.salesReportId && p.partnerId
        ? await dailyAllocations(tx, p.partnerId, p.salesReportId, p.amount)
        : p.allocations.map((a) => ({ invoiceId: a.invoiceId, billId: a.billId, amount: a.amount }));
      await tx.paymentAllocation.deleteMany({ where: { paymentId } }); // pending intentions are replaced by real allocations
      await tx.payment.update({ where: { id: paymentId }, data: { status: "CONFIRMED", verifiedById: actor.id, verifiedAt: new Date(), notes: notes ? `${p.notes ?? ""}\nVerified: ${notes}`.trim() : p.notes } });
      await applyAllocations(tx, paymentId, p.direction, p.amount, intended, p.partnerId);
    } else {
      await tx.payment.update({ where: { id: paymentId }, data: { status: "REJECTED", verifiedById: actor.id, verifiedAt: new Date(), voidReason: notes ?? "Rejected" } });
    }
    await audit(tx, { userId: actor.id, action: approve ? "PAYMENT_VERIFY" : "PAYMENT_REJECT", entityType: "Payment", entityId: paymentId, summary: notes ?? undefined });
    if (p.partnerId) {
      await notifyPartner(p.partnerId, "PAYMENT_SUBMITTED", {
        title: approve ? `Payment ${p.number} confirmed` : `Payment ${p.number} was not accepted`,
        body: approve ? `Thank you. ₱${money(p.amount).toFixed(2)} has been applied.` : notes ?? undefined,
        link: "/portal/invoices", severity: approve ? "INFO" : "WARNING", dedupeKey: `payv-${p.id}`,
      }, tx);
    }
  });
}

export async function voidPayment(actor: Actor, paymentId: string, reason: string) {
  if (!reason?.trim()) throw new AppError("A reason is required to void a payment.");
  return withTx(async (tx) => {
    const p = await tx.payment.findUnique({ where: { id: paymentId } });
    if (!p) throw new NotFoundError("Payment");
    if (p.status !== "CONFIRMED") throw new AppError("Only confirmed payments can be voided.");
    await reverseAllocations(tx, paymentId);
    const after = await tx.payment.update({ where: { id: paymentId }, data: { status: "VOIDED", voidReason: reason } });
    await audit(tx, { userId: actor.id, action: "PAYMENT_VOID", entityType: "Payment", entityId: paymentId, summary: reason, before: p, after });
    return after;
  });
}

/** Records an owner expense: a bill, optionally paid immediately. Counted once in P&L (by bill date). */
export async function recordExpense(actor: Actor, input: BillInput & { paidNow: boolean; method?: PaymentMethod; reference?: string | null; paymentDate?: Date }) {
  return withTx(async (tx) => {
    const bill = await createBill(actor, input, tx);
    if (input.paidNow) {
      await recordPayment(actor, {
        direction: "OUT", paymentDate: input.paymentDate ?? input.billDate, amount: bill.amount, method: input.method ?? "CASH", reference: input.reference,
        partyName: input.payeeName, contactId: input.contactId, partnerId: input.partnerId, allocations: [{ billId: bill.id, amount: bill.amount }],
      }, {}, tx);
    }
    return bill;
  });
}

/** Records other income (machine sale, rental, other): an invoice, optionally received immediately. */
export async function recordIncome(actor: Actor, input: InvoiceInput & { receivedNow: boolean; method?: PaymentMethod; reference?: string | null; partyName: string }) {
  if (input.type === "SUPPLY" || input.type === "PARTNERSHIP_SHARE") throw new AppError("Supply and partnership invoices are generated automatically.");
  return withTx(async (tx) => {
    const inv = await createInvoice(actor, input, tx);
    if (input.receivedNow) {
      await recordPayment(actor, {
        direction: "IN", paymentDate: input.issueDate, amount: inv.amount, method: input.method ?? "CASH", reference: input.reference,
        partyName: input.partyName, partnerId: input.partnerId, contactId: input.contactId, allocations: [{ invoiceId: inv.id, amount: inv.amount }],
      }, {}, tx);
    }
    return inv;
  });
}

// ───────────── Contacts ─────────────

export type ContactInput = { type: ContactType; name: string; contactPerson?: string | null; phone?: string | null; email?: string | null; address?: string | null; notes?: string | null };

export async function saveContact(actor: Actor, input: ContactInput, id?: string) {
  return withTx(async (tx) => {
    const before = id ? await tx.contact.findUnique({ where: { id } }) : null;
    const c = id ? await tx.contact.update({ where: { id }, data: input }) : await tx.contact.create({ data: input });
    await audit(tx, { userId: actor.id, action: id ? "UPDATE" : "CREATE", entityType: "Contact", entityId: c.id, before, after: c });
    return c;
  });
}

// ───────────── Partner operating expenses ─────────────

export async function submitPartnerExpense(actor: Actor, input: { partnerId: string; expenseDate: Date; category: string; description: string; amount: DecimalLike; paidBy: ExpensePaidBy }) {
  const partnerId = actor.role === "PARTNER" ? actor.partnerId! : input.partnerId;
  if (actor.role === "PARTNER" && input.paidBy === "OWNER") throw new AppError("Partners can only submit expenses they paid.");
  const amount = money(input.amount);
  if (amount.lte(0)) throw new AppError("Amount must be greater than zero.");
  return withTx(async (tx) => {
    await assertPeriodOpen(tx, partnerId, input.expenseDate);
    const e = await tx.partnerExpense.create({
      data: { number: await nextCode(tx, "PEX", 5), partnerId, expenseDate: input.expenseDate, category: input.category, description: input.description, amount: amount.toString(), paidBy: input.paidBy, submittedById: actor.id, status: actor.role === "PARTNER" ? "PENDING" : "PENDING" },
    });
    await audit(tx, { userId: actor.id, action: "PARTNER_EXPENSE_SUBMIT", entityType: "PartnerExpense", entityId: e.id, after: e });
    return e;
  });
}

export async function reviewPartnerExpense(actor: Actor, id: string, approve: boolean, notes?: string | null) {
  return withTx(async (tx) => {
    const e = await tx.partnerExpense.findUnique({ where: { id } });
    if (!e) throw new NotFoundError("Expense");
    if (e.status !== "PENDING") throw new AppError("Expense has already been reviewed.");
    await assertPeriodOpen(tx, e.partnerId, e.expenseDate);
    const after = await tx.partnerExpense.update({ where: { id }, data: { status: approve ? "APPROVED" : "REJECTED", reviewNotes: notes, reviewedById: actor.id, reviewedAt: new Date() } });
    await audit(tx, { userId: actor.id, action: approve ? "PARTNER_EXPENSE_APPROVE" : "PARTNER_EXPENSE_REJECT", entityType: "PartnerExpense", entityId: id, before: e, after });
    await notifyPartner(e.partnerId, "GENERAL", { title: `Expense ${e.number} ${approve ? "approved" : "rejected"}`, body: `${e.description} (${fmtDate(e.expenseDate)})${notes ? ` – ${notes}` : ""}`, link: "/portal/expenses", dedupeKey: `pex-${e.id}` }, tx);
    return after;
  });
}

